def valid_reading(value, minimum=0):
    if isinstance(value, bool) or not isinstance(value, (int,float)) or not math.isfinite(value) or value < minimum:
        return None
    return float(value)

def interpolate(raw, points):
    if raw is None or not points or raw < points[0][0] or raw > points[-1][0]: return None
    for (x0,y0),(x1,y1) in zip(points,points[1:]):
        if raw <= x1: return y0+(y1-y0)*(raw-x0)/(x1-x0)
    return points[-1][1]
